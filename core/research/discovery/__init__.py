"""P2 全市场研究截面（Universe Snapshot）子包。

按 P2 计划 §4：
- P2.1 contracts.py：截面字段组与可追溯单元数据契约
- P2.1 universe_snapshot.py：截面构建器（从 P1 仓储按 PIT 组装 9 个字段组）
- P2.1 repository.py：SQLite 持久化 + PIT 过滤 + 幂等迁移 + 不可覆盖
- P2.2 policies.py：版本化 Policy 配置（shadow/active 状态机）
- P2.2 funnel.py：基本面发现漏斗（6 维度独立评分 + Pareto frontier）

设计要点：
- 9 个字段组分开存放，不合并成不可解释总分（P2 §2 强制原则）
- 空字段进入 data_availability 维度，不以零分惩罚（P2.1 验收点 4）
- 截面构建保存 provider / version / coverage / exclusion_reasons（P2.1 验收点 3）
- PIT 过滤：任意 as_of 只能使用 available_at <= as_of 的数据（P2.1 验收点 1）
- 退市/暂停上市/历史成分处理不产生幸存者偏差（P2.1 验收点 2）
- 6 维度独立评分，不强制压成总分（P2.2 §109）
- 维度权重只能通过版本化 policy 配置（P2.2 §111）
- 未经验证的权重只能 shadow，不得成为正式筛选门禁（P2.2 §112）
- 不输出投资建议（AGENTS.md）
"""
